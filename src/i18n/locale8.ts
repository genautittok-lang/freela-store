export function translatePhrase(label: string, locale: string): string {
  if (!isNewLocale(locale)) return label;
  const out = label
    .split(/(\s+)/)
    .map((part) => {
      if (!part.trim()) return part;
      const key = part.toLowerCase().replace(/[^a-z0-9]/g, "");
      const hit = WORDS[key]?.[locale];
      return hit ? hit : part;
    })
    .join("")
    .replace(/\s{2,}/g, " ")
    .trim();
  return out || label;
}

export function translateCta(label: string, locale: string): string {
  if (isNewLocale(locale) && EXACT[label]) return EXACT[label][locale];
  const phrase = translatePhrase(label, locale);
  if (!isNewLocale(locale) || phrase !== label) return phrase;
  const verb = eight("実行", "실행", "运行", "執行", "चलाएँ", "jalankan", "chạy", "เรียกใช้");
  return `${verb[locale]}: ${label}`;
}

