function clamp(text: string, min: number, max: number, pad = "") {
  let trimmed = text.trim();
  if (pad && trimmed.length < min) trimmed = `${trimmed} ${pad}`.trim();
  if (trimmed.length > max) return `${trimmed.slice(0, max - 1).trimEnd()}…`;
  return trimmed;
}

