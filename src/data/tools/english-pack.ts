function t(
  partial: Omit<
    EnTool,
    | "status"
    | "processingMode"
    | "clientOnly"
    | "retention"
    | "deletion"
    | "tested"
    | "translationReviewed"
    | "seoReviewed"
    | "lastReviewedAt"
    | "lastModified"
    | "eventName"
    | "toolVersion"
    | "adSlots"
  > & { status?: EnTool["status"] },
): EnTool {
  return {
    status: "published",
    processingMode: "LOCAL_ONLY",
    clientOnly: true,
    retention: "none",
    deletion: "Inputs stay on this device.",
    tested: true,
    translationReviewed: true,
    seoReviewed: true,
    lastReviewedAt: day,
    lastModified: day,
    eventName: `tool_${partial.id.replace(/-/g, "_")}`,
    toolVersion: "1.0.0",
    adSlots: ["after-result"],
    ...partial,
  };
}

function textCopy(
  name: string,
  title: string,
  description: string,
  h1: string,
  intro: string,
  howTo: [string, string, string],
  faq: [{ question: string; answer: string }, { question: string; answer: string }],
  examples: [string, string],
  formats: string,
  file = false,
) {
  return {
    name,
    title,
    description,
    h1,
    intro,
    howTo,
    faq,
    privacy: file ? privacyFiles.en : privacyText.en,
    formats,
    examples,
  };
}

